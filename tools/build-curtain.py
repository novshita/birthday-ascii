#!/usr/bin/env python3
"""Turn the curtain photo art/curtain.jpg into js/curtain.js: for every cell, how much "strand, bead or butterfly" is
there (the bright detail that stands out from the blurry background) and its colour.   python3 tools/build-curtain.py"""
import base64
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
ROWS, COLS = 160, 213                     # the photo is 2:3 and a cell is half as wide as tall: cols = rows * (2/3) / 0.5
im = Image.open(ROOT / "art" / "curtain.jpg").convert("RGB")
big = np.asarray(im, dtype=float) / 255
lum = big.max(2)
sharp = np.clip((lum - np.asarray(Image.fromarray((lum * 255).astype("uint8")).filter(ImageFilter.GaussianBlur(14)), dtype=float) / 255) * 5 + 0.1, 0, 1)
sat = big.max(2) - big.min(2)
mask = np.clip(sharp * (0.6 + 0.8 * lum), 0, 1)
fg = np.stack([big[..., i] * mask for i in range(3)] + [mask], 2)
small = Image.fromarray((fg * 255).astype("uint8"), "RGBA").convert("RGBa").resize((COLS, ROWS), Image.LANCZOS).convert("RGBA")
a = np.asarray(small)
alpha = a[..., 3]
rgb = a[..., :3].astype(float)
rgb = np.clip(rgb / np.maximum(1, rgb.max(2, keepdims=True)) * 255, 0, 255)           # full brightness: the glow comes from alpha
(ROOT / "js" / "curtain.js").write_text("// Generated by tools/build-curtain.py from art/curtain.jpg. Do not edit by hand.\n"
    "window.CURTAIN = " + json.dumps({"cols": COLS, "rows": ROWS, "a": base64.b64encode(alpha.tobytes()).decode(),
                                     "rgb": base64.b64encode(rgb.astype("uint8").tobytes()).decode()}, separators=(",", ":")) + ";\n")
print("wrote", COLS, "x", ROWS)
