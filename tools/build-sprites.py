#!/usr/bin/env python3
"""Turn the ASCII pictures in art/ into js/sprites.js (brightness maps the page draws, moves and colours itself).
    python3 tools/build-sprites.py
numbers.txt = a sheet of the digits 1-9 (3 x 3), fairy.txt, hbd.txt, flower_animation.txt"""
import base64
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
RAMP = " .:-=+*#%@"


def load(name):
    rows = [l for l in (ROOT / "art" / name).read_text().split("\n") if l != ""]
    w = max(map(len, rows))
    return np.array([[RAMP.index(c) if c in RAMP else 0 for c in r.ljust(w)] for r in rows], float) / 9


def pack(a, lo=0.0, **extra):
    """crop to where there is something brighter than lo, store 0-255 brightness"""
    ys, xs = np.where(a > lo)
    a = a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    return {"cols": a.shape[1], "rows": a.shape[0], "v": base64.b64encode((a * 255).astype("uint8").tobytes()).decode(), **extra}


S = {}
nums = load("numbers.txt")
rb, cb = [0, 31, 60, 97], [0, 33, 64, 100]
for i in range(9):
    r, c = divmod(i, 3)
    S["d%d" % (i + 1)] = pack(nums[rb[r]:rb[r + 1], cb[c]:cb[c + 1]], 0.25)

fairy = load("fairy.txt")
fairy[62:, 58:] = 0                                               # a stray arc in the corner of the original
ys, xs = np.where(fairy > 0.2)
S["fairy"] = pack(fairy, 0.2)
S["fairy"]["tip"] = [round((89 - xs.min()) / S["fairy"]["cols"], 3), round((19.5 - ys.min()) / S["fairy"]["rows"], 3)]      # the wand's tip (the sparkle at her hand)
S["hbd"] = pack(np.where(load("hbd.txt") > 0.3, load("hbd.txt"), 0), 0.0)       # the '.' background and grey corner are not part of the lettering
S["flower"] = pack(load("flower_animation.txt"), 0.25)
(ROOT / "js" / "sprites.js").write_text("// Generated by tools/build-sprites.py from art/*.txt. Do not edit by hand.\nwindow.SPR = "
                                         + json.dumps(S, separators=(",", ":")) + ";\n")
print({k: (v["cols"], v["rows"]) for k, v in S.items()})
