#!/usr/bin/env python3
"""Turn the photos in art/ into js/pics.js: a dense grid of coloured cells for each picture.

    python3 tools/build-pics.py

For each photo: cut out the background (tools/cutout.py), crop to the subject, boost colour and
contrast a little, then shrink it to a grid of character cells. Every cell keeps its real colour.
"""
import base64
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageEnhance, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import cutout  # noqa: E402

ROWS = 170                 # rows of cells per picture
CELL_ASPECT = 0.5          # a character cell is about half as wide as it is tall
# art/<name>.jpg -> points to mark on the picture, in original photo pixels (cake: the cherry stems)
SHARP = {"cake": 170}     # extra local contrast per picture
MARKS = {"cake": [(352, 283), (420, 293), (476, 293), (511, 293), (290, 490), (552, 480)]}


def build(name):
    im = Image.open(ROOT / "art" / (name + ".jpg")).convert("RGB")
    rgba = cutout.cut(name, im)                                  # cut on the original photo...
    vivid = ImageEnhance.Contrast(ImageEnhance.Color(im).enhance(1.6)).enhance(1.2)   # ...then boost the colours
    # local contrast: makes folds, scallops and petal edges stand out, so curves keep their structure
    vivid = vivid.filter(ImageFilter.UnsharpMask(radius=5, percent=SHARP.get(name, 120), threshold=2))
    vivid = vivid.convert("RGBA")
    vivid.putalpha(rgba.split()[3])
    rgba = vivid
    a = np.array(rgba)[..., 3]
    ys, xs = np.where(a > 40)
    x0, x1, y0, y1 = max(0, xs.min() - 6), xs.max() + 7, max(0, ys.min() - 6), ys.max() + 7
    crop = rgba.crop((x0, y0, x1, y1))
    cw, ch = crop.size
    cols = round(ROWS * (cw / ch) / CELL_ASPECT)
    grid = crop.convert("RGBa").resize((cols, ROWS), Image.LANCZOS).convert("RGBA")   # premultiplied resize
    marks = [[round((x - x0) / cw, 4), round((y - y0) / ch, 4)] for x, y in MARKS.get(name, [])]
    return {"cols": cols, "rows": ROWS, "rgba": base64.b64encode(grid.tobytes()).decode(), "marks": marks}


pics = {n: build(n) for n in ("bouquet", "cake", "letter")}
out = ROOT / "js" / "pics.js"
out.write_text("// Generated by tools/build-pics.py from art/*.jpg. Do not edit by hand.\n"
               "window.PICS = " + json.dumps(pics, separators=(",", ":")) + ";\n")
print("wrote", out, {k: (v["cols"], v["rows"]) for k, v in pics.items()}, round(out.stat().st_size / 1024), "KB")
